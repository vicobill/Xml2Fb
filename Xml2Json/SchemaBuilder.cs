using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;
using Xml2Fb.Shared;

namespace Xml2Fb;

class SchemaBuilder
{
    private StringBuilder _stringBuilder = new StringBuilder();

    private readonly Dictionary<string, TableDefinition> _tables = new();
    private readonly Stack<TableDefinition> _context = new();

    public void AddTable( TableDefinition table )
    {
        _tables[table.Name] = table;
        _context.Push( table );
    }

    public bool TryPeek(string tableName,  out TableDefinition table )
    {
        return _tables.TryGetValue( tableName, out table );
    }

    internal void AppendLine(string line)
    {
        _stringBuilder.AppendLine( line );
    }
    

    public override string ToString()
    {
        _stringBuilder.Clear();
        _stringBuilder.AppendLine( "// Auto-generated by XmlToFlatbufferSchemaGenerator" );
        _stringBuilder
            .AppendLine( "include \"basetype.fbs\";" )
            .AppendLine( "namespace Config.ConfigObj;\n" )
            ;


        foreach (var table in _tables.Values.OrderBy( t => t.Name ))
        {
            table.Define( this );
            _stringBuilder.AppendLine();
        }

        if (!string.IsNullOrEmpty( RootType ))
        {
            _stringBuilder.AppendLine( $"root_type {RootType.Capitalize()};" );
        }

        return _stringBuilder.ToString();
    }



    internal void AddVectorField( string name, StructDefinition structDef )
    {
        // 实现向量字段定义
    }
    public string RootType { get; set; }
}
